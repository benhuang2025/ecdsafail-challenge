// returns 1 if HARD, 0 if OK (clean). REALIGNED to 674d0d8 CPU filter
// (+ DIALOG_GCD_K5_TAIL3_TOP32_CODEC=1: reject if last-3-step pattern not in TAIL3_SUP)
// (dialog_gcd_classical_filter.rs::truncated_gcd_step_logged, default flags:
//  STRICT_WIDTH off  -> NO width-overflow fail (tolerate high bits, windowed ops);
//  materialized_sub=false -> body = active-width sub, NO ^1;
//  odd_u=1 -> swap_active_except_bit0; k2=1 + skip_zero_edge=1 -> 2nd shift skips top edge.
//  K5 head/tail codec omitted => slightly conservative (gpu<=cpu), safe for hunting.)
__device__ int check_gcd_factor(const uint64_t*factor,const int*AW,const int*CB,const int*BW,int iters,int k2,int odd_u){
  (void)BW;(void)odd_u; // cf310ec: BW unused (materialized_sub=false), odd_u==1 assumed
  if(g_iszero(factor)) return 1;
  uint64_t u[4],v[4]; g_cp(u,SECP_P); g_cp(v,factor);
  unsigned tp=0; // rolling last-3-step (b0,b0_and_b1,s2) pattern for TAIL3_TOP32 codec
  unsigned hp=0; // first-5-step pattern for HEAD11 codec
  for(int step=0; step<iters; step++){
    int aw=AW[step]; int cb=CB[step];
    int trunc_gt = g_cmp_gt_trunc(u,v,aw,cb);
    int b0 = g_bit(v,0);
    int bb = (b0 && trunc_gt) ? 1 : 0;                       // b0_and_b1
    if(bb){ g_swap_except0(u,v,aw); }                        // swap_active_except_bit0 (odd_u=1)
    if(b0){ uint64_t r[4]; g_sub_low_window(r,v,u,aw); g_cp(v,r); }  // active-width sub, no XOR
    g_shift_right_active(v,aw);                              // shift_right_active(shift_width=aw)
    int s2 = 0;
    if(k2){ s2 = !g_bit(v,0); if(s2){ g_shift_right_active_skip_top_edge(v,aw); } } // s2 = !bit0(v)
    unsigned triple = (unsigned)b0 | ((unsigned)bb<<1) | ((unsigned)s2<<2);
    tp = ((tp>>3) | (triple<<6)) & 0x1FFu;                   // slot2=newest step, slot0=3rd-last
    if(step<5){ hp |= triple << (3*step); }                  // HEAD11 first-5-step pattern (15 bits)
  }
  if(!g_isone(u)) return 1;                                  // hard iff terminal u != 1
  if(!tail3_ok((unsigned short)tp)) return 1;                // 674d0d8: TAIL3_TOP32_CODEC=1
  if(!((HEAD11_MASK[hp>>6]>>(hp&63))&1ULL)) return 1;        // 674d0d8: HEAD11_CODEC=1
  return 0;
}

extern "C" __global__ void test_gcd(const uint64_t*facs,const int*AW,const int*CB,const int*BW,int iters,int k2,int odd_u,int n,int*outhard){
  int i=blockIdx.x*blockDim.x+threadIdx.x; if(i>=n)return;
  uint64_t f[4]; for(int j=0;j<4;j++)f[j]=facs[i*4+j];
  outhard[i]=check_gcd_factor(f,AW,CB,BW,iters,k2,odd_u);
}
