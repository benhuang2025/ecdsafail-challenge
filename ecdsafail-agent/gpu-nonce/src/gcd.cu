// Truncated dialog-GCD filter ported from dialog_gcd_classical_filter.rs.
// accept_u1_terminal semantics: run truncated replay for ITERS steps following
// hardware (truncated) decisions, hard iff WidthOverflow OR final u != 1.
// BodyTrimMismatch + ComparatorMismatch disabled (strict off) to match the
// realigned CPU filter. Assumes odd_u_lowbit_fastpath=true, k2=true.
// Per-step widths aw[]/cb[]/bw[] are precomputed on host (CPU cfg) and uploaded.
__device__ __constant__ uint64_t SECP_P[4] = {0xFFFFFFFEFFFFFC2FULL,0xFFFFFFFFFFFFFFFFULL,0xFFFFFFFFFFFFFFFFULL,0xFFFFFFFFFFFFFFFFULL};

__device__ void g_cp(uint64_t*d,const uint64_t*s){d[0]=s[0];d[1]=s[1];d[2]=s[2];d[3]=s[3];}
__device__ void g_wmask(uint64_t*r,int w){ if(w>=256){r[0]=r[1]=r[2]=r[3]=~0ULL;return;} if(w<=0){r[0]=r[1]=r[2]=r[3]=0ULL;return;} int fw=w>>6,rem=w&63; for(int i=0;i<4;i++){ r[i]=(i<fw)?~0ULL:((i==fw)?(rem?((1ULL<<rem)-1ULL):0ULL):0ULL); } }
__device__ void g_and(uint64_t*r,const uint64_t*a,const uint64_t*b){for(int i=0;i<4;i++)r[i]=a[i]&b[i];}
__device__ void g_andn(uint64_t*r,const uint64_t*a,const uint64_t*m){for(int i=0;i<4;i++)r[i]=a[i]&~m[i];}
__device__ void g_or(uint64_t*r,const uint64_t*a,const uint64_t*b){for(int i=0;i<4;i++)r[i]=a[i]|b[i];}
__device__ int g_gt(const uint64_t*a,const uint64_t*b){for(int i=3;i>=0;i--){if(a[i]>b[i])return 1;if(a[i]<b[i])return 0;}return 0;}
__device__ int g_isone(const uint64_t*a){return a[0]==1ULL&&a[1]==0ULL&&a[2]==0ULL&&a[3]==0ULL;}
__device__ int g_iszero(const uint64_t*a){return (a[0]|a[1]|a[2]|a[3])==0ULL;}
__device__ int g_bit(const uint64_t*x,int i){return (int)((x[i>>6]>>(i&63))&1ULL);}
__device__ int g_bitlen(const uint64_t*x){for(int i=3;i>=0;i--) if(x[i]) return i*64+(64-__clzll(x[i])); return 0;}
__device__ void g_shr(uint64_t*r,const uint64_t*a,int s){ // r=a>>s, 0<=s<256
  if(s==0){g_cp(r,a);return;} int w=s>>6,b=s&63; uint64_t t[4]={0,0,0,0};
  for(int i=0;i<4;i++){int src=i+w; if(src<4){t[i]=a[src]>>b; if(b&&src+1<4)t[i]|=a[src+1]<<(64-b);}} g_cp(r,t);
}
__device__ void g_sub(uint64_t*r,const uint64_t*a,const uint64_t*b){ // r=a-b wrapping (256-bit)
  uint64_t borrow=0;
  for(int i=0;i<4;i++){ uint64_t ai=a[i],bi=b[i]; uint64_t t=ai-bi; uint64_t b1=(ai<bi)?1ULL:0ULL; uint64_t res=t-borrow; uint64_t b2=(t<borrow)?1ULL:0ULL; r[i]=res; borrow=b1|b2; }
}
__device__ int g_cmp_gt_trunc(const uint64_t*u,const uint64_t*v,int w,int cb){
  if(cb>w)cb=w; if(cb<1)cb=1; int lo=w-cb;
  if(cb<=64){ // window of cb<=64 bits fits one u64 -> scalar extract+compare
    int wd=lo>>6, b=lo&63;
    uint64_t us = u[wd]>>b; if(b && wd+1<4) us|=u[wd+1]<<(64-b);
    uint64_t vs = v[wd]>>b; if(b && wd+1<4) vs|=v[wd+1]<<(64-b);
    uint64_t m = (cb>=64)?~0ULL:((1ULL<<cb)-1ULL);
    return (us&m) > (vs&m);
  }
  uint64_t mask[4],us2[4],vs2[4],ua[4],va[4];
  g_wmask(mask,cb); g_shr(us2,u,lo); g_shr(vs2,v,lo); g_and(ua,us2,mask); g_and(va,vs2,mask); return g_gt(ua,va);
}
__device__ void g_sub_low_window(uint64_t*r,const uint64_t*v,const uint64_t*u,int w){
  if(w<=64){ // window fits limb 0 -> single-limb scalar sub (exact)
    uint64_t m=(w>=64)?~0ULL:((1ULL<<w)-1ULL);
    uint64_t d=((v[0]&m)-(u[0]&m))&m;
    r[0]=(v[0]&~m)|d; r[1]=v[1]; r[2]=v[2]; r[3]=v[3]; return;
  }
  uint64_t mask[4],vm[4],um[4],diff[4],hi[4]; g_wmask(mask,w); g_and(vm,v,mask); g_and(um,u,mask);
  g_sub(diff,vm,um); g_and(diff,diff,mask); g_andn(hi,v,mask); g_or(r,hi,diff);
}
__device__ void g_shift_right_active(uint64_t*v,int aw){
  uint64_t mask[4],x[4],xs[4],hi[4]; g_wmask(mask,aw); g_and(x,v,mask); g_shr(xs,x,1); g_andn(hi,v,mask); g_or(v,hi,xs);
}
__device__ void g_swap_except0(uint64_t*u,uint64_t*v,int aw){
  uint64_t maskhi[4],mh[4],uh[4],vh[4]; g_wmask(maskhi,aw); mh[0]=maskhi[0]&~1ULL;mh[1]=maskhi[1];mh[2]=maskhi[2];mh[3]=maskhi[3];
  g_and(uh,u,mh); g_and(vh,v,mh);
  uint64_t nu[4],nv[4]; nu[0]=(u[0]&1ULL)|vh[0];nu[1]=vh[1];nu[2]=vh[2];nu[3]=vh[3];
  nv[0]=(v[0]&1ULL)|uh[0];nv[1]=uh[1];nv[2]=uh[2];nv[3]=uh[3]; g_cp(u,nu);g_cp(v,nv);
}
__device__ void g_shift_right_active_m(uint64_t*v,const uint64_t*mask){
  (void)mask; g_shr(v,v,1); // u,v<2^aw post overflow-check => no bits >=aw => plain >>1
}
__device__ void g_swap_except0_m(uint64_t*u,uint64_t*v,const uint64_t*maskhi){
  (void)maskhi; // u,v<2^aw => swap bits [1,256)==swap [1,aw); keep each bit0
  uint64_t ub0=u[0]&1ULL, vb0=v[0]&1ULL, t;
  t=u[0];u[0]=v[0];v[0]=t; t=u[1];u[1]=v[1];v[1]=t; t=u[2];u[2]=v[2];v[2]=t; t=u[3];u[3]=v[3];v[3]=t;
  u[0]=(u[0]&~1ULL)|ub0; v[0]=(v[0]&~1ULL)|vb0;
}
__device__ void g_shift_right_active_skip_top_edge(uint64_t*v,int aw){
  if(aw<=1) return;
  uint64_t mask[4],x[4],xs[4],lowmask[4],low[4],hi[4]; g_wmask(mask,aw); g_and(x,v,mask);
  g_shr(xs,x,1); g_wmask(lowmask,aw-2); g_and(low,xs,lowmask); g_andn(hi,v,mask);
  int tb=aw-1; uint64_t top=x[tb>>6]&(1ULL<<(tb&63));
  for(int i=0;i<4;i++) v[i]=low[i]|hi[i]; v[tb>>6]|=top;
}
